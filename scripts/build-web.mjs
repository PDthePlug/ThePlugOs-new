import {readFile,writeFile,mkdir,rm,cp} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const root=fileURLToPath(new URL('../',import.meta.url));
const release=JSON.parse(await readFile(path.join(root,'web/release.json'),'utf8'));
if(!/^[a-zA-Z0-9.-]+\.apk$/.test(release.artifact))throw new Error('Invalid artifact filename');
const apk=await readFile(path.join(root,'web/releases',release.artifact));
if(createHash('sha256').update(apk).digest('hex')!==release.sha256)throw new Error('APK digest mismatch; stop publication');
const out=path.join(root,'web-dist');await rm(out,{force:true,recursive:true});await mkdir(path.join(out,'downloads'),{recursive:true});await mkdir(path.join(out,'docs'),{recursive:true});
const tokens={VERSION:release.version,APK_SHA256:release.sha256,NATIVE_COMMIT:release.sourceCommit,APK_FILE:release.artifact,VERIFIED_DATE:release.verifiedDate,TESTS:String(release.automatedTests)};
let html=await readFile(path.join(root,'web/index.html'),'utf8');
for(const [key,value] of Object.entries(tokens))html=html.replaceAll(`__${key}__`,value);
if(/__[A-Z_]+__/.test(html))throw new Error('Unresolved release placeholder');
await writeFile(path.join(out,'index.html'),html);
await cp(path.join(root,'web/styles.css'),path.join(out,'styles.css'));
await cp(path.join(root,'web/app.js'),path.join(out,'app.js'));
await writeFile(path.join(out,'downloads',release.artifact),apk);
await writeFile(path.join(out,'release.json'),JSON.stringify(release,null,2));
for(const file of ['ARCHITECTURE.md','OPERATIONS.md','CONTRACTS.md','STATUS.md','VERIFICATION.md'])await cp(path.join(root,'docs',file),path.join(out,'docs',file));
console.log(`Verified ${release.artifact} SHA-256; static pilot page ready in web-dist`);
